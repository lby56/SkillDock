const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const http = require('node:http');
const { fixture, put, addSkill } = require('./helpers.cjs');
const { fs, path } = require('../src/files.cjs');
(async () => {
  const f = fixture('ai-ui'), root = path.join(f.directory, 'SkillDock 源码 space');
  put(path.join(root, 'package.json'), '{"name":"skilldock","version":"1.6.0"}');
  put(path.join(root, 'src/main.cjs'), 'const title = "SkillDock";\n');
  put(path.join(root, 'src/renderer/style.css'), 'body { color: red; }\n');
  addSkill(f.manager, 'codex', 'example-skill');
  let mode = 'normal'; const calls = [];
  const server = http.createServer(async (req, res) => {
    let body = ''; for await (const chunk of req) body += chunk;
    const data = JSON.parse(body); calls.push({ path: req.url, headers: req.headers, data });
    const probe = data.messages?.at(-1)?.content === '只回复 OK，不要使用工具。';
    const content = probe ? 'OK' : JSON.stringify({ summary: '调整 SkillDock 界面颜色并添加功能模块。', changes: [{ path: 'src/renderer/style.css', content: 'body { color: blue; }\n' }, { path: 'src/new-feature.cjs', content: 'module.exports = { enabled: true };\n' }] });
    if (mode === 'slow') await new Promise(resolve => setTimeout(resolve, 2000));
    res.writeHead(200, { 'Content-Type': 'application/json' }); res.end(JSON.stringify({ choices: [{ finish_reason: 'stop', message: { content } }] }));
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const env = { ...process.env, SKILLDOCK_HOME: f.home, SKILLDOCK_DATA: f.dataDir }; delete env.ELECTRON_RUN_AS_NODE;
  const app = await electron.launch({ executablePath: process.env.SKILLDOCK_TEST_EXE || require('electron'), args: process.env.SKILLDOCK_TEST_EXE ? [] : [path.join(__dirname, '..')], env });
  const page = await app.firstWindow(), errors = [], checks = [];
  page.on('pageerror', error => errors.push(error.message));
  const pass = text => { checks.push(text); console.log(`PASS ${text}`); };
  try {
    await page.waitForSelector('#navigation [data-route="ai"]'); await page.locator('#navigation [data-route="ai"]').click();
    await page.waitForSelector('#ai-root');
    await page.locator('#ai-root').fill(root); await page.locator('[data-action="ai-save-root"]').click();
    await page.waitForSelector('[data-ai-file="src/renderer/style.css"]');
    assert.ok((await page.locator('#ai-root').inputValue()).includes('源码 space'));
    pass('real Electron renderer reads a chosen source folder and lists editable context');
    await page.locator('[data-action="ai-new-profile"]').click();
    await page.locator('#ai-name').fill('本机测试 API');
    await page.locator('#ai-model').fill('test-model');
    await page.locator('#ai-url').fill(`http://127.0.0.1:${server.address().port}/v1`);
    await page.locator('#ai-key').fill('local-test-private-key');
    await page.locator('[data-action="ai-save-profile"]').click();
    await page.waitForFunction(() => document.querySelector('#ai-profile')?.selectedOptions[0]?.textContent.includes('本机测试 API'));
    const settings = await page.evaluate(() => window.skilldock.call('aiSettings'));
    assert.equal(settings.profiles.find(p => p.name === '本机测试 API').hasKey, true);
    assert.ok(!fs.readFileSync(path.join(f.dataDir, 'ai-settings.json'), 'utf8').includes('local-test-private-key'));
    pass('connection saves a real Windows-encrypted Key and masks it from renderer');
    await page.locator('[data-action="ai-probe"]').click();
    await page.waitForFunction(() => document.querySelector('#toast')?.textContent.includes('连接成功'));
    assert.equal(calls[0].path, '/v1/chat/completions'); assert.equal(calls[0].headers.authorization, 'Bearer local-test-private-key');
    pass('test connection makes a real HTTP provider request with the configured endpoint and headers');
    await page.locator('#ai-prompt').fill('把界面颜色改为蓝色，并添加一个功能模块。');
    await page.locator('[data-action="ai-generate"]').click();
    await page.waitForSelector('.ai-diffs');
    assert.equal(fs.readFileSync(path.join(root, 'src/renderer/style.css'), 'utf8'), 'body { color: red; }\n');
    assert.equal(await page.locator('.ai-diffs details').count(), 2);
    assert.ok(calls[1].data.messages[1].content.includes('src/renderer/style.css'));
    await page.screenshot({ path: path.join(__dirname, '../qa/ai-preview.png'), fullPage: true });
    pass('natural-language request reaches API and previews actual file changes without writing');
    await page.locator('[data-action="ai-apply"]').click();
    await page.waitForFunction(() => document.querySelector('[data-action="ai-apply"]')?.textContent.includes('已应用'));
    assert.equal(fs.readFileSync(path.join(root, 'src/renderer/style.css'), 'utf8'), 'body { color: blue; }\n');
    assert.ok(fs.existsSync(path.join(root, 'src/new-feature.cjs')));
    await page.locator('[data-action="ai-undo"]').click();
    await page.waitForFunction(() => document.querySelector('.ai-history')?.textContent.includes('已恢复'));
    assert.equal(fs.readFileSync(path.join(root, 'src/renderer/style.css'), 'utf8'), 'body { color: red; }\n');
    assert.equal(fs.existsSync(path.join(root, 'src/new-feature.cjs')), false);
    pass('apply writes real files with persistent backup; restore recovers originals and removes added files');
    mode = 'slow'; await page.locator('[data-action="ai-generate"]').click();
    await page.waitForSelector('[data-action="ai-cancel"]');
    await page.locator('#navigation [data-route="overview"]').click();
    await page.waitForSelector('[data-overview-skill="example-skill"]');
    await page.locator('#navigation [data-route="ai"]').click();
    await page.waitForSelector('[data-action="ai-cancel"]'); await page.locator('[data-action="ai-cancel"]').click();
    await page.waitForFunction(() => document.querySelector('#ai-job')?.textContent.includes('已取消'));
    pass('generation keeps navigation responsive and supports cancellation');
    mode = 'normal';
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1080, 720));
    for (const colorScheme of ['light', 'dark']) {
      await page.emulateMedia({ colorScheme });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth || document.querySelector('main').scrollWidth > document.querySelector('main').clientWidth), false);
      await page.screenshot({ path: path.join(__dirname, `../qa/ai-compact-${colorScheme}.png`) });
    }
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1440, 930));
    await page.emulateMedia({ colorScheme: 'light' }); await page.screenshot({ path: path.join(__dirname, '../qa/ai-workbench.png') });
    assert.deepEqual(errors, []);
    pass('light and dark workbench fit minimum window size without overflow or renderer errors');
    fs.writeFileSync(path.join(__dirname, '../qa/ai-ui-report.json'), JSON.stringify({ passed: true, checks, errors, providerCalls: calls.length, at: new Date().toISOString() }, null, 2));
  } finally { await app.close(); await new Promise(resolve => server.close(resolve)); }
})().catch(error => { console.error(error); process.exitCode = 1; });
